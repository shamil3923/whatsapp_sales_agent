def _text(product):
    return " ".join([
        product["name"], product["brand"], product["category"],
        product.get("description", ""),
        " ".join(f"{k}: {v}" for k, v in (product.get("specs") or {}).items()),
    ]).lower()


def name_has(*fragments):
    """Products whose name contains every fragment (case-insensitive)."""
    def predicate(products):
        return [p["sku"] for p in products
                if all(f.lower() in p["name"].lower() for f in fragments)]
    return predicate


def spec_has(key, *fragments):
    def predicate(products):
        out = []
        for p in products:
            value = str((p.get("specs") or {}).get(key, "")).lower()
            if all(f.lower() in value for f in fragments):
                out.append(p["sku"])
        return out
    return predicate


def category(*names):
    def predicate(products):
        return [p["sku"] for p in products if p["category"] in names]
    return predicate


def text_has(*fragments):
    def predicate(products):
        return [p["sku"] for p in products
                if all(f.lower() in _text(p) for f in fragments)]
    return predicate


def where(fn):
    def predicate(products):
        return [p["sku"] for p in products if fn(p)]
    return predicate


def combine(*predicates):
    """Intersection, preserving catalog order."""
    def predicate(products):
        sets = [set(p(products)) for p in predicates]
        keep = set.intersection(*sets) if sets else set()
        return [p["sku"] for p in products if p["sku"] in keep]
    return predicate


def union(*predicates):
    def predicate(products):
        keep = set()
        for p in predicates:
            keep |= set(p(products))
        return [p["sku"] for p in products if p["sku"] in keep]
    return predicate


def cheapest(n, inner=None):
    def predicate(products):
        pool = products
        if inner is not None:
            keep = set(inner(products))
            pool = [p for p in products if p["sku"] in keep]
        return [p["sku"] for p in sorted(pool, key=lambda p: p["price_usd"])[:n]]
    return predicate


def nothing():
    return lambda products: []


def under(amount):
    return where(lambda p: p["price_usd"] < amount)


def between(low, high):
    return where(lambda p: low <= p["price_usd"] <= high)


