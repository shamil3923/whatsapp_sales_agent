#!/usr/bin/env python3
"""
Build evals/datasets/retrieval.jsonl: 100 shopping queries with gold SKUs.

Two rules govern how this dataset is built, both aimed at the same failure:
a benchmark that reports a high score because it was easy.

1. Queries are written from the customer's side, not the catalog's. They were
   written first, as things a person would type into WhatsApp, and only then
   matched to products. Nothing here is generated by paraphrasing a product
   description, which is the standard way a retrieval benchmark ends up
   reporting Recall@3 = 1.0 while telling you nothing: if the query is a
   restatement of the document, retrieving it is trivial.

   So the set deliberately includes misspellings ("thinkpaid", "macbok"),
   colloquial model names ("sony xm5"), dropped brand words ("samsung s24
   ultra" for a Galaxy), run-together tokens ("xps13"), wrong brand
   attribution, vague budget language ("nothing over a grand"), multi-constraint
   requests, need-statements that never name a product ("my eyes hurt after
   work"), and competitor brands that are not stocked.

2. Gold sets come from explicit predicates over the catalog, not from
   eyeballing search results. Each query carries a `gold_rule` describing its
   predicate in words, so a reader can audit any label without rerunning
   anything. Labelling from a retriever's own output would bake that
   retriever's behaviour into the ground truth.

The out-of-catalog slice has empty gold sets on purpose. It measures whether a
retriever knows when to return nothing, which matters more for a sales agent
than ranking quality: a confident wrong answer becomes a false promise to a
customer.

    python evals/datasets/build_retrieval_dataset.py
"""
