def main() -> int:
    products = read_catalog_file(DEFAULT_CATALOG_PATH)

    records, problems = [], []
    for index, (query, cat, note, predicate, rule) in enumerate(QUERIES, start=1):
        gold = predicate(products)
        record = {
            "id": f"q{index:03d}",
            "query": query,
            "category": cat,
            "note": note,
            "gold_skus": gold,
            "gold_rule": rule,
        }
        records.append(record)

        # An in-catalog query with no gold SKUs is a broken predicate, not a
        # hard query, and would silently score 0 for every retriever.
        if cat != "out_of_catalog" and not gold:
            problems.append(f"{record['id']} {query!r}: predicate matched nothing")
        if cat == "out_of_catalog" and gold:
            problems.append(f"{record['id']} {query!r}: expected empty gold set")

    if problems:
        print("Dataset problems:", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False) + "\n")

    by_category = {}
    for record in records:
        by_category.setdefault(record["category"], []).append(record)

    print(f"Wrote {len(records)} queries to {OUT_PATH}")
    for cat, rows in sorted(by_category.items()):
        sizes = [len(r["gold_skus"]) for r in rows]
        if cat == "out_of_catalog":
            print(f"  {cat:<18} {len(rows):>3} queries, gold sets empty by design")
        else:
            print(f"  {cat:<18} {len(rows):>3} queries, "
                  f"gold set size min {min(sizes)} / median "
                  f"{sorted(sizes)[len(sizes) // 2]} / max {max(sizes)}")
    return 0


